import 'dotenv/config';

const DEFAULT_GITHUB_TOKEN = process.env.GITHUB_TOKEN;
const DEFAULT_GITHUB_REPO = process.env.GITHUB_REPO || 'sandman-sh/00-Flake';

/**
 * Validates a GitHub repo URL or owner/repo and tests token permissions.
 */
export async function verifyGitHubConnection({ repo = DEFAULT_GITHUB_REPO, token = DEFAULT_GITHUB_TOKEN }) {
  const cleanRepo = repo.replace(/^https?:\/\/github\.com\//i, '').replace(/\.git$/i, '').trim();
  const [owner, repoName] = cleanRepo.split('/');

  if (!owner || !repoName) {
    return {
      valid: false,
      error: 'Invalid repository format. Please use "owner/repo" or "https://github.com/owner/repo".'
    };
  }

  const activeToken = token && token !== 'your_github_token_here' ? token : DEFAULT_GITHUB_TOKEN;

  const headers = {
    'Accept': 'application/vnd.github+json',
    'User-Agent': '00-Flake-Agent-Harness'
  };

  if (activeToken && activeToken !== 'your_github_token_here') {
    headers['Authorization'] = `Bearer ${activeToken}`;
  }

  try {
    const res = await fetch(`https://api.github.com/repos/${owner}/${repoName}`, { headers });
    if (!res.ok) {
      if (res.status === 404) {
        return {
          valid: false,
          error: `Repository "${cleanRepo}" not found (or is private and requires a valid GitHub Token).`
        };
      }
      if (res.status === 401) {
        return {
          valid: false,
          error: 'Invalid or expired GitHub Personal Access Token.'
        };
      }
      return {
        valid: false,
        error: `GitHub API returned status ${res.status}.`
      };
    }

    const data = await res.json();
    return {
      valid: true,
      repo: data.full_name,
      defaultBranch: data.default_branch,
      description: data.description || 'Connected GitHub Repository',
      isPrivate: data.private,
      stars: data.stargazers_count,
      openIssues: data.open_issues_count,
      hasToken: Boolean(activeToken && activeToken !== 'your_github_token_here')
    };
  } catch (err) {
    return {
      valid: false,
      error: `Network error connecting to GitHub: ${err.message}`
    };
  }
}

